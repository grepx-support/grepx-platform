"""scripts/run.sh contracts - write one contract module per service into platform/libs/grepx-contracts.

A contract is what other code may rely on: the service's name, its request table, the state tables it owns,
and the enums in its src/dto/ (actions, fields, reason codes). Callers import it instead of typing strings:

    from grepx_contracts import donor
    gw.command(donor.REQUESTS, donor.SERVICE, {"action": donor.DonorAction.CREATE, ...})
    gw.rows(donor.DONORS, email=...)

    scripts/run.sh contracts          regenerate
    scripts/run.sh contracts --check  fail when a contract is out of date (CI)
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import yaml

from log import say
from workspace import ROOT, known_services as registry

OUT = ROOT / "platform" / "libs" / "grepx-contracts" / "grepx_contracts"
PROBE = r'''
import enum, importlib, json, sys, pkgutil
sys.path.insert(0, sys.argv[1])
dto = importlib.import_module("dto")
mods = [dto] + [importlib.import_module("dto." + m.name) for m in pkgutil.iter_modules(dto.__path__)]
out = {}
for mod in mods:
    for name, obj in vars(mod).items():
        if isinstance(obj, type) and issubclass(obj, enum.Enum) and obj.__module__.startswith("dto") and name not in out:
            out[name] = [[m.name, m.value] for m in obj]
print(json.dumps(out))
'''


def module_name(service: str) -> str:
    return service.removesuffix("-service").replace("-", "_")


def enums_of(src: Path) -> dict:
    if not (src / "dto").exists():
        return {}
    run = subprocess.run([sys.executable, "-c", PROBE, str(src)], capture_output=True, text=True, cwd=src)
    if run.returncode:
        raise SystemExit(f"cannot read {src}/dto: {run.stderr.strip().splitlines()[-1]}")
    return json.loads(run.stdout)


def render(service: str, cfg: dict, enums: dict) -> str:
    owns = list(cfg.get("owns") or [])
    lines = [f'"""{service} contract - generated by `scripts/run.sh contracts` from its config.yaml and src/dto/. Do not edit."""',
             "from enum import Enum", "", f'SERVICE = "{service}"', f'REQUESTS = "{cfg["snapshot_table"]}"']
    lines += [f'{t.upper()} = "{t}"' for t in owns]
    lines += [f"OWNS = ({', '.join(t.upper() for t in owns)}{',' if len(owns) == 1 else ''})"]
    for name, members in sorted(enums.items()):
        lines += ["", "", f"class {name}(str, Enum):"] + [f"    {m} = {json.dumps(v)}" for m, v in members]
    return "\n".join(lines) + "\n"


def build(with_enums: bool = True) -> dict[str, str]:
    files = {}
    for service, svc in registry().items():
        cfg_file = svc["path"] / "config" / "config.yaml"
        if not cfg_file.exists() or not (svc["path"] / "src" / "dto").exists():
            continue
        cfg = yaml.safe_load(cfg_file.read_text(encoding="utf-8")) or {}
        if cfg.get("snapshot_table"):
            files[module_name(service)] = render(service, cfg, enums_of(svc["path"] / "src") if with_enums else {})
    names = sorted(files)
    files["__init__"] = ('"""grepx_contracts - every service\'s published names (generated; see platform/tools/grepx_tools/contracts.py)."""\n'
                         + "".join(f"from . import {n}\n" for n in names) + f"\n__all__ = {json.dumps(names)}\n")
    return files


def main(check: bool = False) -> int:
    if not check:
        # a service's dto may import other contracts: write names-only modules first, so every import resolves
        OUT.mkdir(parents=True, exist_ok=True)
        for name, text in build(with_enums=False).items():
            if name == "__init__" or not (OUT / f"{name}.py").exists():     # the index must list every module before dtos import them
                (OUT / f"{name}.py").write_text(text, encoding="utf-8")
    files = build()
    stale = [n for n, text in files.items() if not (OUT / f"{n}.py").exists() or (OUT / f"{n}.py").read_text(encoding="utf-8") != text]
    stale += [p.stem for p in OUT.glob("*.py") if p.stem not in files]
    if check:
        if stale:
            say("ERROR", "contracts", f"out of date: {', '.join(stale)} - run scripts/run.sh contracts")
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.py"):
        if old.stem not in files:
            old.unlink()                     # a service was renamed or removed
    for name, text in files.items():
        (OUT / f"{name}.py").write_text(text, encoding="utf-8")
    say("OK", "contracts", f"{len(files) - 1} service contracts in platform/libs/grepx-contracts")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
