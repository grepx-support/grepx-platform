"""Service catalogue - the registry you search BEFORE building a new service.

    scripts/run.sh catalog          # writes catalog/services.json + docs/SERVICE_CATALOG.md
    scripts/run.sh find email     # which services already do this?
    scripts/run.sh show task-service

Everything is read from the services themselves (config.yaml, dto enums, docstrings, table
constants), so the catalogue can never drift from the code. Rule: reuse a common service if it
fits; extend it only with product-agnostic behaviour; otherwise scaffold a new one with
scripts/run.sh new (common-services/ if any other product could use it, else product-services/<p>/).
"""
from __future__ import annotations

import ast
import json
import re
import sys
from pathlib import Path

import yaml

from root import ROOT  # noqa: E402  (the workspace, see root.py)
LAYERS = {"common-services": "common", "product-services": "product", "apps": "app"}


def _enum_values(path: Path) -> list[str]:
    return re.findall(r'^\s+[A-Z_]+ = "([^"]+)"', path.read_text(encoding="utf-8"), re.M)


def _doc(path: Path) -> str:
    try:
        return (ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or "").strip().splitlines()[0]
    except (SyntaxError, IndexError, FileNotFoundError):
        return ""


def describe(config: Path) -> dict:
    base = config.parent.parent
    cfg = yaml.safe_load(config.read_text(encoding="utf-8")) or {}
    src, rel = base / "src", base.relative_to(ROOT)
    dto = list((src / "dto").glob("*.py")) if (src / "dto").exists() else []
    actions = sorted({v for p in dto if p.name.endswith("_action.py") for v in _enum_values(p)})
    reasons = sorted({v for p in dto if p.name == "reason_code.py" for v in _enum_values(p)})
    text = "\n".join(p.read_text(encoding="utf-8") for p in src.rglob("*.py")) if src.exists() else ""
    tables = sorted(set(re.findall(r'_TABLE\s*=\s*"([a-z_]+)"', text)) | set(re.findall(r'"([a-z_]+_requests)"', text)) - {cfg.get("snapshot_table")})
    routes = sorted(p.stem for p in (src / "routes").glob("*.py") if p.stem not in ("__init__", "common", "dispatch")) if (src / "routes").exists() else []
    return {"name": cfg.get("service_name", base.name), "layer": LAYERS.get(rel.parts[0], rel.parts[0]),
            "product": rel.parts[1] if rel.parts[0] == "product-services" else "", "path": rel.as_posix(),
            "request_table": cfg.get("snapshot_table", ""), "actions": actions, "reasons": reasons, "other_tables": tables,
            "summary": cfg.get("description") or _doc(src / "main.py"), "routes": routes,
            "reacts_to": sorted(set(re.findall(r'Subscription\("([a-z_]+)"', text)))}


def build() -> list[dict]:
    services = [describe(c) for c in sorted(ROOT.glob("*-services/**/config/config.yaml")) if "test" not in c.parts]
    out = ROOT / "catalog"
    out.mkdir(exist_ok=True)
    (out / "services.json").write_text(json.dumps(services, indent=2), encoding="utf-8")
    lines = ["# Service catalogue", "", "_Generated by `scripts/run.sh catalog` - do not edit by hand._", "",
             "Search here before building anything new: `scripts/run.sh find <word>`.", ""]
    for layer in ("common", "product"):
        lines += [f"## {layer.title()} services", "", "| Service | Request table | Actions | Also uses | Summary |", "|---|---|---|---|---|"]
        for s in (s for s in services if s["layer"] == layer):
            lines.append(f"| `{s['name']}`{' (' + s['product'] + ')' if s['product'] else ''} | {'`' + s['request_table'] + '`' if s['request_table'] else '(watches only)'} | "
                         f"{', '.join(s['actions'])} | {', '.join(s['other_tables'] + [t + ' (reacts)' for t in s['reacts_to']])} | {s['summary']} |")
        lines.append("")
    (ROOT / "docs" / "SERVICE_CATALOG.md").write_text("\n".join(lines), encoding="utf-8")
    return services


def find(word: str, services: list[dict]) -> list[dict]:
    word = word.lower()
    return [s for s in services if word in json.dumps(s).lower()]


if __name__ == "__main__":
    cmd, *args = sys.argv[1:] or ["build"]
    services = build()
    if cmd == "find":
        for s in find(" ".join(args), services):
            print(f"{s['layer']:8} {s['name']:28} {s['path']}\n         actions: {', '.join(s['actions'])}\n         {s['summary']}")
    elif cmd == "show":
        print(json.dumps(next((s for s in services if s["name"] == args[0]), {}), indent=2))
    else:
        print(f"{len(services)} services catalogued -> catalog/services.json, docs/SERVICE_CATALOG.md")
