"""Add (or refresh) the GrepX proprietary header in every source file of every GrepX repo, in each file type's own
comment syntax.

    scripts/run.sh headers                 the workspace and the repos next to it (grepx-platform, grepx-services,
                                           grepx-nexus-cpp): add / update headers
    scripts/run.sh headers --dry-run       only show what would change
    scripts/run.sh headers --remove        take the headers out again
    scripts/run.sh headers PATH [PATH…]    only these folders

Safe to run many times: an existing GrepX header (also the older LifeFlow one) is recognised and replaced, never
duplicated. Shebangs and Python encoding lines stay on top. Generated files, third-party code (external/), JSON and
binary files are left alone.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from datetime import date
from pathlib import Path

from root import ROOT  # noqa: E402

COMPANY, WEBSITE = "GrepX Private Limited", "grepx.sg"
MARKER = "Copyright (c)"            # the first header line starts with this and names the company
LINES = [f"{MARKER} {date.today().year} {COMPANY} ({WEBSITE}). All rights reserved.",
         "This file is part of the GrepX platform and is proprietary and confidential.",
         "Unauthorised copying, use, modification or distribution is strictly prohibited."]
SKIP_DIRS = {"venv", ".venv", ".git", "__pycache__", "node_modules", "instance", "_to_delete", ".idea", ".vscode",
             "external", "build", "data", "logs", "run", "dist", ".pytest_cache"}
SKIP_PATHS = ("platform/libs/grepx-contracts/grepx_contracts/",   # generated by scripts/run.sh contracts
              "docs/SERVICE_CATALOG.md", "catalog/")               # generated by scripts/run.sh catalog
REPOS = ("grepx-platform", "grepx-services", "grepx-nexus-cpp")   # siblings of the workspace


class CommentStyle:
    """How one file type writes comments. Subclasses only describe syntax (Open/Closed)."""
    def block(self, lines): raise NotImplementedError
    def pattern(self): raise NotImplementedError
    def keep_first(self, line): return False


class LineComment(CommentStyle):
    def __init__(self, prefix): self.prefix = prefix
    def block(self, lines): return "\n".join(f"{self.prefix} {l}" for l in lines) + "\n"

    def pattern(self):
        p = re.escape(self.prefix)
        return re.compile(rf"(?:{p} [^\n]*\n)*?{p} {re.escape(MARKER)}[^\n]*{re.escape(COMPANY)}[^\n]*\n(?:{p} [^\n]*\n)*\n?")


class HashComment(LineComment):
    """Python, shell, YAML, requirements, CMake, .env: shebang and encoding lines stay on top."""
    def __init__(self): super().__init__("#")
    def keep_first(self, line): return line.startswith("#!") or re.match(r"#.*coding[:=]", line) is not None


class BlockComment(CommentStyle):
    def __init__(self, start, end, inner=" "): self.start, self.end, self.inner = start, end, inner
    def block(self, lines): return self.start + "\n" + "\n".join(self.inner + l for l in lines) + "\n" + self.end + "\n"

    def pattern(self):
        s, e = re.escape(self.start), re.escape(self.end)
        return re.compile(rf"{s}\n(?:(?!{e})[^\n]*\n)*?[^\n]*{re.escape(MARKER)}[^\n]*{re.escape(COMPANY)}"
                          rf"[^\n]*\n(?:(?!{e})[^\n]*\n)*{e}\n\n?")


class HtmlComment(BlockComment):
    """<!-- --> after the <!doctype …> line (nothing may come before it in a page)."""
    def __init__(self): super().__init__("<!--", "-->", "  ")
    def keep_first(self, line): return line.lstrip().lower().startswith("<!doctype")


C_STYLE, JINJA, HTML = BlockComment("/*", " */", " * "), BlockComment("{#", "#}", "  "), HtmlComment()
STYLES = {".py": HashComment(), ".sh": HashComment(), ".txt": HashComment(), ".yaml": HashComment(), ".yml": HashComment(),
          ".cmake": HashComment(), ".example": HashComment(), ".env": HashComment(),
          ".js": C_STYLE, ".css": C_STYLE, ".c": C_STYLE, ".h": C_STYLE, ".cpp": C_STYLE, ".hpp": C_STYLE, ".cc": C_STYLE,
          ".md": HTML, ".sql": LineComment("--")}


def style_for(path: Path):
    if path.suffix.lower() in (".html", ".j2"):
        # Jinja templates get {# #} (never reaches the browser or an email); plain pages get <!-- -->
        return JINJA if "templates" in path.parts or path.suffix.lower() == ".j2" else HTML
    return STYLES.get(path.suffix.lower()) or STYLES.get(path.name.lower())


class HeaderTool:
    def __init__(self, roots, dry_run=False, remove=False): self.roots, self.dry, self.remove = roots, dry_run, remove

    def files(self, root: Path):
        for folder, dirs, names in os.walk(root):          # links are not followed: each repo is visited once, as itself
            dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith("cmake-build") and not d.endswith(".egg-info"))
            for name in sorted(names):
                path = Path(folder) / name
                rel = path.relative_to(root).as_posix()
                if not path.is_symlink() and not any(rel.startswith(s) or rel == s for s in SKIP_PATHS) and style_for(path):
                    yield path

    def process(self, path: Path) -> str:
        raw = path.read_bytes()
        if b"\0" in raw:
            return "skipped (binary)"
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            return "skipped (not UTF-8)"
        newline = "\r\n" if "\r\n" in text else "\n"
        text = text.replace("\r\n", "\n")
        style = style_for(path)
        head, body = self._split_top(text, style)
        had = bool(style.pattern().match(body))
        body = style.pattern().sub("", body, count=1) if had else body
        result = head + body if self.remove else head + style.block(LINES) + ("\n" if body.strip() else "") + body.lstrip("\n")
        if result == text:
            return "unchanged"
        if not self.dry:
            path.write_bytes(result.replace("\n", newline).encode("utf-8"))
        return ("removed" if self.remove else "updated" if had else "added") + (" (dry run)" if self.dry else "")

    @staticmethod
    def _split_top(text, style):
        lines = text.splitlines(keepends=True)
        n = 0
        while n < len(lines) and n < 2 and style.keep_first(lines[n]):
            n += 1
        return "".join(lines[:n]), "".join(lines[n:])

    def run(self) -> int:
        for root in self.roots:
            counts: dict[str, int] = {}
            for path in self.files(root):
                status = self.process(path)
                counts[status] = counts.get(status, 0) + 1
                if status.startswith("skipped"):
                    print(f"{status:>22}  {path.relative_to(root)}")
            print(f"{root.name}: " + (", ".join(f"{v} {k}" for k, v in sorted(counts.items())) or "no files"))
        return 0


def default_roots() -> list[Path]:
    """This workspace (the product repo) plus the GrepX repos next to it."""
    return [ROOT] + [ROOT.parent / r for r in REPOS if (ROOT.parent / r).is_dir()]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("paths", nargs="*", type=Path)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--remove", action="store_true")
    a = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    return HeaderTool([p.resolve() for p in a.paths] or default_roots(), a.dry_run, a.remove).run()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
